/* Adds a "copy page source" button to Furo's header icon row, beside the
   view-source / edit / theme-toggle icons.

   Sphinx publishes every page's raw source under _sources/ (index.md.txt,
   autoapi/micm_nlp/config/index.rst.txt, …). Finding that URL from JS takes a little
   care:

   * Furo's existing icons cannot be reused. With html_theme_options.source_repository
     set they point at GitHub, not at _sources/, so there is no local link to read.
   * DOCUMENTATION_OPTIONS carries SOURCELINK_SUFFIX but, as of Sphinx 7.4, no longer
     carries URL_ROOT — so the site root is recovered from the resolved src of the
     documentation_options.js script tag instead.
   * The source extension is not exposed at all. Authored pages are .md, pages
     generated by sphinx-autoapi are .rst, so both are probed and whichever responds
     is used. Either is fine to paste into a model.

   The button reports failure in its tooltip rather than failing silently: the
   Clipboard API needs a secure context, so this will not work over plain http or
   from a file:// copy of the build. */

(function () {
  'use strict';

  const COPY_ICON =
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"' +
    ' fill="none" stroke="currentColor" stroke-width="1" stroke-linecap="round"' +
    ' stroke-linejoin="round"><rect x="9" y="9" width="11" height="11" rx="2"/>' +
    '<path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"/></svg>';

  const DONE_ICON =
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"' +
    ' fill="none" stroke="currentColor" stroke-width="1" stroke-linecap="round"' +
    ' stroke-linejoin="round"><path d="M20 6 9 17l-5-5"/></svg>';

  const DEFAULT_TITLE = 'Copy this page’s source for an LLM';

  function siteRoot() {
    const script = document.querySelector('script[src*="documentation_options.js"]');
    if (!script) {
      return null;
    }
    // …/_static/documentation_options.js  ->  …/
    return script.src.replace(/_static\/documentation_options\.js.*$/, '');
  }

  function pageName(root) {
    const path = decodeURIComponent(window.location.pathname);
    const rootPath = decodeURIComponent(new URL(root, window.location.href).pathname);
    let name = path.startsWith(rootPath) ? path.slice(rootPath.length) : path.replace(/^\//, '');
    if (name === '' || name.endsWith('/')) {
      name += 'index';
    }
    return name.replace(/\.html$/, '');
  }

  function sourceCandidates() {
    const root = siteRoot();
    if (!root) {
      return [];
    }
    const options = window.DOCUMENTATION_OPTIONS || {};
    const suffix = options.SOURCELINK_SUFFIX !== undefined ? options.SOURCELINK_SUFFIX : '.txt';
    const name = pageName(root);
    return ['.md', '.rst'].map(function (extension) {
      return root + '_sources/' + name + extension + suffix;
    });
  }

  function flash(button, icon, title) {
    button.innerHTML = icon;
    button.setAttribute('title', title);
    window.setTimeout(function () {
      button.innerHTML = COPY_ICON;
      button.setAttribute('title', DEFAULT_TITLE);
    }, 1800);
  }

  /* Not every page has a source. sphinx.ext.viewcode generates a highlighted listing
     per module under _modules/, and those have no _sources counterpart — roughly a
     third of the built pages. Probe first so the button only appears where it works,
     rather than appearing everywhere and failing on click. */
  async function resolveSourceUrl() {
    for (const url of sourceCandidates()) {
      try {
        const response = await fetch(url, { method: 'HEAD' });
        if (response.ok) {
          return url;
        }
      } catch (error) {
        return null;
      }
    }
    return null;
  }

  async function copySource(button, url) {
    try {
      const response = await fetch(url);
      if (!response.ok) {
        throw new Error('HTTP ' + response.status);
      }
      await navigator.clipboard.writeText(await response.text());
      flash(button, DONE_ICON, 'Copied');
    } catch (error) {
      flash(button, COPY_ICON, 'Copy failed: ' + error.message);
    }
  }

  async function install() {
    const container = document.querySelector('.content-icon-container');
    if (!container || !siteRoot()) {
      return;
    }

    const sourceUrl = await resolveSourceUrl();
    if (!sourceUrl) {
      return;
    }

    const button = document.createElement('a');
    // Borrow a sibling icon's classes so this matches the theme in both colour
    // schemes without hard-coding any of Furo's own styling.
    const sibling = container.querySelector('a, button');
    button.className = sibling ? sibling.className : 'muted-link content-icon';
    button.setAttribute('role', 'button');
    button.setAttribute('tabindex', '0');
    button.setAttribute('title', DEFAULT_TITLE);
    button.style.cursor = 'pointer';
    button.innerHTML = COPY_ICON;
    button.addEventListener('click', function (event) {
      event.preventDefault();
      copySource(button, sourceUrl);
    });

    container.insertBefore(button, container.firstChild);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', install);
  } else {
    install();
  }
})();
